#!/usr/bin/env bash
# Regenerate _data/gallery.yml — the ordered list the Gallery page renders.
#
# Photos in assets/img/gallery/ are ordered by the date the photo was taken
# (EXIF DateTimeOriginal), NEWEST FIRST. Images without EXIF (e.g. ones whose
# metadata was stripped) fall back to their file modification time.
#
# Jekyll/Liquid can't read EXIF at build time, so we precompute the order here.
# Re-run this whenever you add or remove images in assets/img/gallery/:
#     bash bin/gen_gallery.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DIR="$ROOT/assets/img/gallery"
OUT="$ROOT/_data/gallery.yml"
MAGICK="$(command -v magick || echo /usr/local/bin/magick)"

rows=""
while IFS= read -r f; do
  base="$(basename "$f")"
  key=""
  d="$("$MAGICK" identify -format '%[EXIF:DateTimeOriginal]' "$f" 2>/dev/null | head -1 || true)"
  if [ -n "$d" ]; then                           # 1) EXIF "YYYY:MM:DD HH:MM:SS" -> epoch
    key="$(date -j -f '%Y:%m:%d %H:%M:%S' "$d" +%s 2>/dev/null || true)"
  fi
  if [ -z "$key" ]; then                         # 2) a YYYY-MM-DD date in the filename (e.g. WhatsApp)
    fd="$(printf '%s' "$base" | grep -oE '[0-9]{4}-[0-9]{2}-[0-9]{2}' | head -1 || true)"
    if [ -n "$fd" ]; then
      ft="$(printf '%s' "$base" | grep -oE '[0-9]{2}\.[0-9]{2}\.[0-9]{2}' | head -1 | tr '.' ':' || true)"
      [ -z "$ft" ] && ft="12:00:00"
      key="$(date -j -f '%Y-%m-%d %H:%M:%S' "$fd $ft" +%s 2>/dev/null || true)"
    fi
  fi
  if [ -z "$key" ]; then
    key="$(stat -f %m "$f")"                     # 3) last resort: file modification time
  fi
  rows+="${key}|${base}"$'\n'
done < <(find "$DIR" -maxdepth 1 -type f \( -iname '*.jpg' -o -iname '*.jpeg' -o -iname '*.png' \))

{
  echo "# Auto-generated by bin/gen_gallery.sh — do not edit by hand."
  echo "# assets/img/gallery/ photos ordered by date taken (newest first),"
  echo "# falling back to file modification time when EXIF date is missing."
  printf '%s' "$rows" | sort -t'|' -k1,1 -rn | while IFS='|' read -r key base; do
    [ -n "$base" ] && echo "- /assets/img/gallery/$base"
  done
} > "$OUT"

echo "Wrote $OUT ($(printf '%s' "$rows" | grep -c . ) images)"
